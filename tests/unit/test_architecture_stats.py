"""``docs/ARCHITECTURE.md``'s Key Statistics must describe the tree.

The section is generated by ``scripts/architecture_stats.py``. This test
re-measures the repository and fails when a documented count drifts more
than 10% (the version and the coverage gate must match exactly). Regenerate
with ``python scripts/architecture_stats.py --write docs/ARCHITECTURE.md``.
"""

from __future__ import annotations

import dataclasses
import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]

_spec = importlib.util.spec_from_file_location(
    "architecture_stats", ROOT / "scripts" / "architecture_stats.py"
)
assert _spec is not None and _spec.loader is not None
stats_script = importlib.util.module_from_spec(_spec)
# Registered first: the script's dataclass resolves its module by name.
sys.modules[_spec.name] = stats_script
_spec.loader.exec_module(stats_script)

DOC = ROOT / "docs" / "ARCHITECTURE.md"


@pytest.fixture(scope="module")
def actual():
    return stats_script.compute_stats(ROOT)


def test_documented_stats_match_the_tree(actual) -> None:
    documented = stats_script.parse_section(DOC.read_text(encoding="utf-8"))
    problems = stats_script.drift(documented, actual)
    assert not problems, (
        "docs/ARCHITECTURE.md Key Statistics are stale; regenerate with "
        "`python scripts/architecture_stats.py --write docs/ARCHITECTURE.md`:\n  "
        + "\n  ".join(problems)
    )


def test_stats_measure_the_package(actual) -> None:
    assert actual.package_modules > 100
    assert actual.package_lines > actual.package_modules
    assert actual.test_files > 100
    assert actual.coverage_gate > 0
    assert actual.helm_profiles > 0


def test_rendered_section_round_trips(actual) -> None:
    text = "# Doc\n\n" + stats_script.render_section(actual) + "\n### Next\n"
    parsed = stats_script.parse_section(text)
    assert stats_script.drift(parsed, actual) == []
    assert parsed.version == actual.version
    assert parsed.package_modules == actual.package_modules


def test_drift_beyond_tolerance_is_reported(actual) -> None:
    stale = dataclasses.replace(
        actual,
        package_lines=int(actual.package_lines * 0.85),
        test_files=int(actual.test_files * 0.95),
        version="0.0.1",
    )
    problems = stats_script.drift(stale, actual)
    assert any(p.startswith("package_lines") for p in problems)
    assert any(p.startswith("version") for p in problems)
    assert not any(p.startswith("test_files") for p in problems)


def test_write_replaces_only_the_section(tmp_path: Path, actual) -> None:
    doc = tmp_path / "ARCHITECTURE.md"
    doc.write_text(
        "# Title\n\n### Key Statistics (0.1.0)\n\n- **~1 lines** stale\n\n"
        "### Design Philosophy\n\nkept\n",
        encoding="utf-8",
    )
    stats_script.write_section(doc, actual)
    text = doc.read_text(encoding="utf-8")
    assert text.startswith("# Title\n\n### Key Statistics (")
    assert text.endswith("### Design Philosophy\n\nkept\n")
    assert stats_script.drift(stats_script.parse_section(text), actual) == []
