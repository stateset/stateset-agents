"""Compute the headline numbers in ``docs/ARCHITECTURE.md``'s Key Statistics.

The section used to be written by hand and went stale (it described 0.41.0
long after). This script measures the repository instead:

* the package version (``[project] version`` in ``pyproject.toml``);
* production Python in ``stateset_agents/``: physical lines and modules;
* tests under ``tests/``: physical lines of every ``.py`` file and the number
  of ``test_*.py`` files;
* the coverage gate (``[tool.coverage.report] fail_under``);
* the Helm value profiles (``deployment/helm/stateset-agents/values-*.yaml``,
  each rendered by ``tests/unit/test_helm_chart_renders.py``).

Usage::

    python scripts/architecture_stats.py                 # print the stats
    python scripts/architecture_stats.py --section       # print the markdown
    python scripts/architecture_stats.py --write docs/ARCHITECTURE.md
    python scripts/architecture_stats.py --check docs/ARCHITECTURE.md

``--check`` exits 1 when the document's counts drift more than 10% from the
tree (the version and the coverage gate must match exactly);
``tests/unit/test_architecture_stats.py`` runs the same comparison.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

try:
    import tomllib  # Python 3.11+
except ModuleNotFoundError:  # pragma: no cover - Python 3.10
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "ARCHITECTURE.md"
HELM_CHART = Path("deployment") / "helm" / "stateset-agents"

#: Largest relative difference tolerated between a documented count and the
#: tree before the document counts as stale.
TOLERANCE = 0.10

_HEADING = re.compile(r"^### Key Statistics \((?P<version>[^)]+)\)\s*$", re.M)


@dataclass(frozen=True)
class ArchitectureStats:
    """What the Key Statistics section states."""

    version: str
    package_lines: int
    package_modules: int
    test_lines: int
    test_files: int
    coverage_gate: int
    helm_profiles: int


def _python_files(directory: Path) -> list[Path]:
    return [
        path
        for path in sorted(directory.rglob("*.py"))
        if "__pycache__" not in path.parts
    ]


def _line_count(paths: list[Path]) -> int:
    return sum(path.read_bytes().count(b"\n") for path in paths)


def compute_stats(root: Path = ROOT) -> ArchitectureStats:
    """Measure the repository at ``root``."""
    pyproject = tomllib.loads((root / "pyproject.toml").read_text("utf-8"))
    package = _python_files(root / "stateset_agents")
    tests = _python_files(root / "tests")
    return ArchitectureStats(
        version=str(pyproject["project"]["version"]),
        package_lines=_line_count(package),
        package_modules=len(package),
        test_lines=_line_count(tests),
        test_files=sum(1 for path in tests if path.name.startswith("test_")),
        coverage_gate=int(pyproject["tool"]["coverage"]["report"]["fail_under"]),
        helm_profiles=len(list((root / HELM_CHART).glob("values-*.yaml"))),
    )


def _thousands(value: int) -> str:
    return f"~{round(value / 1000) * 1000:,}"


def render_section(stats: ArchitectureStats) -> str:
    """The Key Statistics section (heading included) for ``stats``."""
    return f"""### Key Statistics ({stats.version})

Generated by `scripts/architecture_stats.py`;
`tests/unit/test_architecture_stats.py` fails when a count drifts more than
10% from the tree.

- **{_thousands(stats.package_lines)} lines** of production Python in \
`stateset_agents/` ({stats.package_modules} modules)
- **{_thousands(stats.test_lines)} lines** of tests across `tests/` \
({stats.test_files} test files; {stats.coverage_gate}% coverage gate
  enforced in CI via `[tool.coverage.report] fail_under = {stats.coverage_gate}`)
- **9 RL algorithms** with dedicated trainer classes: GRPO (TRL bridge),
  GSPO, GEPO, DAPO, VAPO, PPO, RLAIF, plus offline RL (BCQ/BEAR/CQL/IQL/DT)
- **10+ pre-built reward functions** plus composable LLM-judge and rule
  adapters under `stateset_agents/rewards/`
- **{stats.helm_profiles} Helm value profiles** (A100/H100/B200, GKE examples; \
per-model
  Kimi-K2.5, GLM-5.1/5.2, Qwen-3.5 variants) rendered by
  `tests/unit/test_helm_chart_renders.py`
- **Async-first** design throughout the API, agent, and trainer surfaces
- **Reproducibility-first releases:** lock files (`requirements-lock.txt`,
  `requirements-dev-lock.txt`) checked in CI; nightly benchmark regression
  alerts at 150% threshold
"""


def _section_bounds(text: str) -> tuple[int, int]:
    match = _HEADING.search(text)
    if match is None:
        raise ValueError("no '### Key Statistics (<version>)' heading")
    following = re.compile(r"^#{1,3} ", re.M).search(text, match.end())
    return match.start(), following.start() if following else len(text)


def parse_section(text: str) -> ArchitectureStats:
    """The counts a document's Key Statistics section states."""
    start, end = _section_bounds(text)
    section = text[start:end]

    def number(pattern: str) -> int:
        found = re.search(pattern, section, re.S)
        if found is None:
            raise ValueError(f"Key Statistics has no match for {pattern!r}")
        return int(found.group(1).replace(",", ""))

    heading = _HEADING.search(section)
    assert heading is not None
    return ArchitectureStats(
        version=heading.group("version"),
        package_lines=number(r"\*\*~([\d,]+) lines\*\* of production Python"),
        package_modules=number(r"`stateset_agents/` \((\d+) modules\)"),
        test_lines=number(r"\*\*~([\d,]+) lines\*\* of tests"),
        test_files=number(r"\((\d+) (?:test )?files;"),
        coverage_gate=number(r"fail_under = (\d+)"),
        helm_profiles=number(r"\*\*(\d+) Helm value profiles\*\*"),
    )


def drift(documented: ArchitectureStats, actual: ArchitectureStats) -> list[str]:
    """Each documented value that disagrees with the tree."""
    problems = []
    for name in ("version", "coverage_gate"):
        want, got = getattr(actual, name), getattr(documented, name)
        if want != got:
            problems.append(f"{name}: documented {got}, actual {want}")
    for name in (
        "package_lines",
        "package_modules",
        "test_lines",
        "test_files",
        "helm_profiles",
    ):
        want, got = getattr(actual, name), getattr(documented, name)
        if abs(got - want) > TOLERANCE * max(1, want):
            problems.append(
                f"{name}: documented {got}, actual {want} "
                f"(more than {TOLERANCE:.0%} apart)"
            )
    return problems


def write_section(path: Path, stats: ArchitectureStats) -> None:
    """Replace ``path``'s Key Statistics section with :func:`render_section`."""
    text = path.read_text(encoding="utf-8")
    start, end = _section_bounds(text)
    path.write_text(text[:start] + render_section(stats) + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--section", action="store_true", help="print the markdown")
    group.add_argument("--write", type=Path, help="rewrite this document's section")
    group.add_argument("--check", type=Path, help="fail on drift in this document")
    args = parser.parse_args(argv)
    stats = compute_stats()
    if args.write is not None:
        write_section(args.write, stats)
        print(f"wrote Key Statistics to {args.write}")
        return 0
    if args.check is not None:
        try:
            problems = drift(parse_section(args.check.read_text("utf-8")), stats)
        except ValueError as error:
            problems = [str(error)]
        for problem in problems:
            print(f"stale: {problem}", file=sys.stderr)
        if problems:
            print(
                "regenerate: python scripts/architecture_stats.py --write "
                f"{args.check}",
                file=sys.stderr,
            )
        return 1 if problems else 0
    if args.section:
        print(render_section(stats), end="")
        return 0
    print(json.dumps(asdict(stats), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
